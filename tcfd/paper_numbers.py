"""Recompute every number quoted in the paper text that is not printed in a table.

Reads results/metrics.csv, results/cp.csv (written by tcfd.evaluate), the Jetson logits and bench.csv,
and writes results/paper_numbers.md, one line per claim, grouped by paper section.

    python -m tcfd.paper_numbers -c config.yaml
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from .config import base_parser, load_config, path
from .metrics import reliability, softmax

ARCHS = {"resnet1d": "ResNet-1D", "wdcnn": "WDCNN"}
DEV = ["fp32", "fp16", "int8_src", "int8_all"]  # Jetson engines (excludes workstation PyTorch "ws_fp32")


def rng(s: pd.Series, fmt="{:.3f}") -> str:
    return f"{fmt.format(s.min())}--{fmt.format(s.max())}"


class Out:
    def __init__(self):
        self.lines: list[str] = []

    def h(self, t):
        self.lines += ["", f"## {t}", ""]

    def __call__(self, claim, value):
        self.lines.append(f"- {claim}: **{value}**")


def per_fold(M, C, arch, src, shifted):
    """Per-fold summary per (ratio, precision), same definitions as Table II (tcfd.report.main_table)."""
    Mr = M[(M.arch == arch) & (M.split == "test") & (M.calib == "raw")]
    Mt = M[(M.arch == arch) & (M.split == "test") & (M.calib == "ts")]
    Cc = C[(C.arch == arch) & (C.split == "test") & (C.score == "lac")]
    rows = []
    for (fold, r, p), g in Mr.groupby(["fold", "ratio", "precision"]):
        g = g.set_index("cond")
        gt = Mt[(Mt.fold == fold) & (Mt.ratio == r) & (Mt.precision == p)].set_index("cond")
        cs = Cc[(Cc.fold == fold) & (Cc.ratio == r) & (Cc.precision == p)]
        row = {"fold": fold, "ratio": r, "precision": p, "bacc_src": g.loc[src, "bacc"],
               "bacc_shift": g.loc[shifted, "bacc"].mean(), "ece_shift": g.loc[shifted, "ece"].mean(),
               "ece_shift_ts": gt.loc[shifted, "ece"].mean() if len(gt) else np.nan,
               "agree": g.loc[shifted, "agree_dense"].mean()}
        for v in cs.variant.unique():
            cv = cs[cs.variant == v]
            row[f"covmin_{v}"] = cv.coverage.min()
            row[f"covmean_{v}"] = cv.coverage.mean()
            row[f"size_{v}"] = cv.set_size.mean()
            for c in cv.cond:
                row[f"cov_{v}_{c}"] = cv[cv.cond == c].coverage.iloc[0]
        rows.append(row)
    return pd.DataFrame(rows)


def logits_pairs(jd: Path, folds, arch, prec, ref, conds):
    """Yield (fold, model, cond, logits_prec, logits_ref) for all Jetson engines of one architecture."""
    for f in folds:
        for md in sorted((jd / f).glob(f"{arch}_p*")):
            for c in conds:
                a, b = md / prec / f"test_{c}.npy", md / ref / f"test_{c}.npy"
                if a.exists() and b.exists():
                    yield f, md.name, c, np.load(a), np.load(b)


def main():
    args = base_parser("Recompute the in-text numbers of the paper").parse_args()
    cfg = load_config(args.config)
    res = path(cfg, cfg["analysis"]["results_dir"])
    M, C = pd.read_csv(res / "metrics.csv"), pd.read_csv(res / "cp.csv")
    src = cfg["source_condition"]
    conds = list(cfg["conditions"])
    shifted = [c for c in conds if c != src]
    jd = path(cfg, cfg["jetson"]["out_dir"]) / "logits"
    exp = path(cfg, cfg["export"]["dir"])
    folds = sorted(M.fold.unique())
    o = Out()
    o.lines += ["# In-text numbers of the paper", "",
                "Regenerated by `python -m tcfd.paper_numbers -c config.yaml`. Values are means over the three "
                "bearing-wise folds of TensorRT engines on the Jetson unless stated otherwise; `std` is across folds.",
                f"Source condition: {src}; shifted conditions: {', '.join(shifted)}; LAC conformal sets, "
                f"alpha = {cfg['analysis']['alpha']}."]

    # --- Section: input representation (workstation FP32, dense ResNet) -------------------------------
    o.h("Input representation and training data (workstation PyTorch FP32, dense ResNet-1D)")
    w = M[(M.arch == "resnet1d") & (M.ratio == 0) & (M.precision == "ws_fp32") & (M.split == "test")
          & (M.calib == "raw")]
    o("bAcc at source condition (final configuration)", f"{w[w.cond == src].bacc.mean():.3f}")
    o("bAcc mean over shifted conditions (final configuration)",
      f"{w[w.cond.isin(shifted)].groupby('fold').bacc.mean().mean():.3f}")
    o("FFT and no-artificial-damage numbers (0.41-0.51; 0.63/0.55)",
      "see results_ablation_fft/ and results_ablation_noart/")

    # --- Baseline under shift --------------------------------------------------------------------------
    o.h("Baseline under operating-point shift (dense ResNet-1D, Jetson FP32)")
    d = M[(M.arch == "resnet1d") & (M.ratio == 0) & (M.precision == "fp32") & (M.split == "test")
          & (M.calib == "raw")].groupby("cond")[["bacc", "ece"]].mean()
    for c in conds:
        o(f"{c}: bAcc / ECE (uncalibrated)", f"{d.loc[c, 'bacc']:.3f} / {d.loc[c, 'ece']:.3f}")
    P, Y = [], []
    for f in folds:
        for c in shifted:
            p = jd / f / "resnet1d_p00" / "fp32" / f"test_{c}.npy"
            if p.exists():
                P.append(softmax(np.load(p)))
                Y.append(np.load(exp / f / "data" / f"test_{c}_y.npy"))
    if P:
        P, Y = np.concatenate(P), np.concatenate(Y)
        hi = P.max(1) > 0.9
        o("Shifted windows with confidence > 0.9: accuracy (fraction of windows)",
          f"{(P.argmax(1)[hi] == Y[hi]).mean():.3f} ({hi.mean():.2f})")
        _, acc, n, edges = reliability(P, Y, cfg["analysis"]["ece_bins"])
        o("Reliability diagram, top bin accuracy (confidence > %.3f)" % edges[-2], f"{acc[-1]:.3f} (n={n[-1]})")

    # --- Accuracy hides what compression changes --------------------------------------------------------
    for arch, an in ARCHS.items():
        pf = per_fold(M, C, arch, src, shifted)
        if pf.empty:
            continue
        pf = pf[pf.precision.isin(DEV)]
        mean = pf.groupby(["ratio", "precision"]).mean(numeric_only=True)
        std = pf.groupby(["ratio", "precision"]).std(numeric_only=True)
        o.h(f"Compression vs. trust: {an} ({len(mean)} configurations, Table II definitions)")
        o("bAcc at source, range over configurations", rng(mean.bacc_src))
        o("bAcc mean over shift, range over configurations", rng(mean.bacc_shift))
        pr = mean[mean.index.get_level_values(0) > 0]
        o("Agreement with dense FP32 under shift, pruned configurations", rng(pr.agree))
        o("  ... i.e. disagreement (%)", f"{(1 - pr.agree.max()) * 100:.0f}--{(1 - pr.agree.min()) * 100:.0f}")
        e = mean.xs("fp32", level=1).ece_shift
        o("Uncalibrated ECE under shift, FP32 by pruning ratio",
          ", ".join(f"{int(r * 100)}%: {v:.3f}" for r, v in e.items()))
        o("Fold-to-fold std of uncalibrated shifted ECE, max over configurations", f"{std.ece_shift.max():.3f}")
        if mean.ece_shift_ts.notna().any():
            o("Temperature-scaled ECE under shift: dense FP32", f"{mean.loc[(0.0, 'fp32'), 'ece_shift_ts']:.3f}")
            o("Temperature-scaled ECE under shift, compressed configurations",
              rng(mean[mean.index != (0.0, "fp32")].ece_shift_ts))
        v = M[(M.arch == arch) & (M.ratio == 0) & (M.precision == "fp32") & (M.calib == "raw") & (M.cond == src)]
        o("Dense FP32 bAcc at source: val-fit bearings vs. test bearings",
          f"{v[v.split == 'valfit'].bacc.mean():.3f} vs. {v[v.split == 'test'].bacc.mean():.3f}")

        # precision agreement from logits
        for prec in ("fp16", "int8_src", "int8_all"):
            ag = [(lg.argmax(1) == rf.argmax(1)).mean() for *_, lg, rf in logits_pairs(jd, folds, arch, prec, "fp32", conds)]
            if ag:
                o(f"{prec} vs. FP32 engine label agreement: mean / min over (fold, ratio, condition)",
                  f"{np.mean(ag):.4f} / {np.min(ag):.4f}")
        for prec in ("int8_src", "int8_all"):
            dif = (mean.xs(prec, level=1).bacc_shift - mean.xs("fp32", level=1).bacc_shift).abs()
            dsrc = (mean.xs(prec, level=1).bacc_src - mean.xs("fp32", level=1).bacc_src).abs()
            o(f"|bAcc({prec}) - bAcc(FP32)|, max over ratios (source / shift)", f"{dsrc.max():.3f} / {dif.max():.3f}")

        # conformal coverage
        o.h(f"Conformal coverage: {an}")
        if "covmin_src" in mean:
            o("Source-calibrated CP, worst-condition coverage: dense FP32",
              f"{mean.loc[(0.0, 'fp32'), 'covmin_src']:.3f}")
            o("Source-calibrated CP, worst-condition coverage, all configurations", rng(mean.covmin_src))
            o("Source-calibrated CP, coverage at C1, all configurations", rng(mean[f"cov_src_{shifted[0]}"]))
        for v in ("pooled", "mondrian"):
            if f"covmin_{v}" in mean:
                o(f"{v} CP (validation bearings), worst-condition coverage, all configurations",
                  rng(mean[f"covmin_{v}"]))
        if "covmin_mondrian" in mean:
            for c in conds:
                o(f"Op.-point CP on validation bearings, coverage at {c}, all configurations",
                  rng(mean[f"cov_mondrian_{c}"]))
        if "covmin_lobo_mondrian" in mean:
            k = (0.0, "fp32")
            o("Bearing-level op.-point CP, dense FP32: worst-condition coverage",
              f"{mean.loc[k, 'covmin_lobo_mondrian']:.3f} ± {std.loc[k, 'covmin_lobo_mondrian']:.3f}")
            o("Bearing-level op.-point CP, dense FP32: mean coverage over conditions",
              f"{mean.loc[k, 'covmean_lobo_mondrian']:.3f}")
            o("Bearing-level op.-point CP, dense FP32: mean set size", f"{mean.loc[k, 'size_lobo_mondrian']:.2f}")
            o("Bearing-level op.-point CP, worst-condition coverage, all configurations",
              rng(mean.covmin_lobo_mondrian))
            o("  ... fold-to-fold std, range over configurations", rng(std.covmin_lobo_mondrian, "{:.2f}"))
            for c in conds:
                o(f"Bearing-level op.-point CP, coverage at {c}, all configurations",
                  rng(mean[f"cov_lobo_mondrian_{c}"]))
            for prec in ("int8_src", "int8_all"):
                dd = (mean.xs(prec, level=1).covmin_lobo_mondrian - mean.xs("fp32", level=1).covmin_lobo_mondrian).abs()
                o(f"|worst-cond. coverage({prec}) - FP32| under bearing-level CP, max over ratios", f"{dd.max():.3f}")

    # --- INT8 calibration data ------------------------------------------------------------------------
    o.h("INT8 calibration data (source-only vs. all conditions)")
    for arch, an in ARCHS.items():
        dev = {}
        for prec in ("int8_src", "int8_all"):
            mx = [np.abs(lg - rf).max() for *_, lg, rf in logits_pairs(jd, folds, arch, prec, "fp32", shifted)]
            dev[prec] = max(mx) if mx else np.nan
        o(f"{an}: largest |logit(INT8) - logit(FP32)| under shift, all-cond. vs. source-only calibration",
          f"{dev['int8_all']:.2f} vs. {dev['int8_src']:.2f}")
    # same definition as Fig. (fig_int8_calib): per (fold, model, ratio, condition), all four conditions
    d = M[(M.split == "test") & (M.calib == "raw") & M.precision.isin(["int8_src", "int8_all"])]
    pe = d.pivot_table(index=["fold", "arch", "ratio", "cond"], columns="precision", values="ece").dropna()
    o("Mean ECE difference all-cond. minus source-only calibration (both models, all ratios, folds, conditions)",
      f"{(pe.int8_all - pe.int8_src).mean():+.3f}")
    for v, lab in (("src", "source-calibrated CP"), ("lobo_mondrian", "bearing-level op.-point CP")):
        cc = C[(C.split == "test") & (C.score == "lac") & (C.variant == v) & C.precision.isin(["int8_src", "int8_all"])]
        if cc.empty:
            continue
        pc = cc.pivot_table(index=["fold", "arch", "ratio", "cond"], columns="precision", values="coverage").dropna()
        o(f"Mean coverage difference all-cond. minus source-only ({lab}, same grouping)",
          f"{(pc.int8_all - pc.int8_src).mean():+.3f}")

    # --- Jetson cost ---------------------------------------------------------------------------------
    bf = path(cfg, cfg["jetson"]["out_dir"]) / "bench" / "bench.csv"
    if bf.exists():
        b = pd.read_csv(bf)
    if bf.exists() and {"trt_gpu_median_ms", "py_lat_p50_ms", "dyn_energy_mj_per_inf"} <= set(b.columns):
        o.h(f"Deployment cost on the Jetson (bench.csv, fold(s) {', '.join(sorted(b.fold.astype(str).unique()))})")
        for arch, an in ARCHS.items():
            x = b[b.arch == arch]
            if x.empty:
                continue
            d0 = x[(x.ratio == 0) & (x.precision == "fp32")].iloc[0]
            o(f"{an} dense FP32: GPU median latency / dynamic energy",
              f"{d0.trt_gpu_median_ms:.3f} ms / {d0.dyn_energy_mj_per_inf:.2f} mJ")
            rmax = x.ratio.max()
            sel = x[((x.ratio == 0) & (x.precision != "fp32")) | (x.ratio == rmax)]
            o(f"{an}: dense FP16/INT8 and {int(rmax * 100)}%-pruned (any precision): GPU latency range",
              f"{sel.trt_gpu_median_ms.min():.3f}--{sel.trt_gpu_median_ms.max():.3f} ms")
            o(f"{an}: same engines, dynamic energy range", rng(sel.dyn_energy_mj_per_inf, "{:.2f}") + " mJ")
            o(f"{an}: same engines, speed-up / energy reduction vs. dense FP32",
              f"{(d0.trt_gpu_median_ms / sel.trt_gpu_median_ms).min():.1f}--{(d0.trt_gpu_median_ms / sel.trt_gpu_median_ms).max():.1f}x / "
              f"{(d0.dyn_energy_mj_per_inf / sel.dyn_energy_mj_per_inf).min():.1f}--{(d0.dyn_energy_mj_per_inf / sel.dyn_energy_mj_per_inf).max():.1f}x")
            o(f"{an}: GPU latency range over all engines", rng(x.trt_gpu_median_ms) + " ms")
            o(f"{an}: best speed-up over dense FP32 (any engine)", f"{(d0.trt_gpu_median_ms / x.trt_gpu_median_ms).max():.1f}x")
        o("End-to-end Python call (p50), range over all engines", rng(b.py_lat_p50_ms, "{:.2f}") + " ms")
        win_s = 4096 / 4000  # 4096-sample envelope windows at 4 kHz
        o("Real-time margin: window length / slowest end-to-end p50", f"{win_s * 1e3 / b.py_lat_p50_ms.max():.0f}x")

    # --- Deployment rules ----------------------------------------------------------------------------
    sp = res / "selection.csv"
    if sp.exists():
        s = pd.read_csv(sp)
        o.h("Accuracy-only vs. trust-aware deployment (selection.csv; also in Table IV)")
        num = s.select_dtypes("number").columns
        g = s.groupby([c for c in ("arch", "rule", "variant") if c in s.columns])[list(num)].mean()
        o.lines += ["", "```", g.round(3).to_string(), "```"]

    out = res / "paper_numbers.md"
    out.write_text("\n".join(o.lines) + "\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    main()
